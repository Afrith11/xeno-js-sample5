window.getProductById = function(id) {
  if (!id) return window.ATELIER_PRODUCTS[0];
  return window.ATELIER_PRODUCTS.find(p => p.id === id || p.code.toLowerCase() === id.toLowerCase()) || window.ATELIER_PRODUCTS[0];
};

